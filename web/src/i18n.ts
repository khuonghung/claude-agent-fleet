export type Key = keyof typeof en;
export const DICTIONARIES: Record<Lang, Dict> = { en, vi, ja, ko, zh };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const dict = DICTIONARIES[lang] ?? en;
  return (key, vars) => (dict[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ""));
}

export function pickLanguage(stored: string | null, mission: string | undefined, browser: string | undefined): Lang {
  const known = (value: string | null | undefined): Lang | undefined => LANGUAGES.find((l) => value?.toLowerCase().startsWith(l.id))?.id;
  return known(stored) ?? known(mission) ?? known(browser) ?? "en";
}

export interface I18n {
  lang: Lang;
  locale: string;
  t: T;
}

export const I18nContext = createContext<I18n>({ lang: "en", locale: "en-GB", t: translator("en") });
export const useI18n = (): I18n => useContext(I18nContext);
